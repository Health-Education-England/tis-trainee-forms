package uk.nhs.hee.tis.trainee.forms.annotations;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;
import org.springframework.security.access.prepost.PreAuthorize;

/**
 * Restricts a method to the admin currently assigned to the LTFT form identified by the method's
 * {@code id} parameter.
 *
 * <p>Method-level {@code @PreAuthorize} overrides the class-level one, so the LTFT admin role
 * check is repeated here.
 */
@Target({ElementType.METHOD, ElementType.TYPE})
@Retention(RetentionPolicy.RUNTIME)
@Documented
@PreAuthorize("hasRole('NHSE_LTFT_Admin') and @assignedAdminAuthorizer.isAssignedAdmin(#id)")
public @interface IsAssignedAdmin {

}
